"""Observability measurements, rendered as a Markdown report.

Every figure is computed from the records and describes what the reviewed
public record shows. None of it is an assessment of whether any issuer or
trustee complied with any obligation.
"""

from collections import Counter, defaultdict
from datetime import date
from statistics import median

from brdo.consistency import compare_notices_with_reports, compare_statements_with_reports, revisions
from brdo.status import derive_all
from brdo.store import Dataset
from brdo.vocab import (
    CONTRACT_DOCUMENT_TYPES,
    ActionKind,
    Agreement,
    CovenantSpecificity,
    CoverageStatus,
    DocumentType,
    InstrumentProperty,
    NoticeKind,
    SearchOutcome,
    SearchPurpose,
    SourceKind,
)


def _table(header: list[str], rows: list[list[object]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join("" if cell is None else str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def _spread(values: list[int]) -> str:
    if not values:
        return "n/a"
    return f"{min(values)} / {median(values):g} / {max(values)} (n={len(values)})"


def breach_reported_isins(dataset: Dataset) -> set[str]:
    return {isin for report in dataset.breach_reports.values() for row in report.rows for isin in row.isins}


def linkage_funnel(dataset: Dataset) -> list[tuple[str, int]]:
    """How far each ISIN listed in a breach report can be traced towards its contract."""
    listed = breach_reported_isins(dataset)
    notices = [n for n in dataset.breach_notices.values() if n.kind is NoticeKind.BREACH]
    named = {isin for n in notices if n.isins_printed for isin in n.isins} & listed
    with_deed = {isin for n in notices if n.deed_dates for isin in n.isins} & listed
    text_printed = {
        isin
        for report in dataset.breach_reports.values()
        for row in report.rows
        for item in row.items
        if item.specificity in (CovenantSpecificity.CLAUSE_TEXT, CovenantSpecificity.REQUIREMENT_AND_ACTUAL)
        for isin in item.isins
    }
    transcribed = {isin for provision in dataset.provisions.values() for isin in provision.instruments} & listed
    located = {
        search.subject
        for search in dataset.searches.values()
        if search.purpose is SearchPurpose.CONTRACT_DOCUMENT and search.outcome is SearchOutcome.LOCATED_NOT_RETRIEVED
    } & listed
    retrieved = {
        isin
        for isin in listed
        for link in dataset.instruments[isin].documents
        if dataset.documents[link.document].type in CONTRACT_DOCUMENT_TYPES
    }
    links = [
        (isin, link)
        for report in dataset.breach_reports.values()
        for row in report.rows
        for item in row.items
        for link in item.provisions
        for isin in item.isins
        if isin in dataset.provisions[link.provision].instruments
    ]
    linked = {isin for isin, _ in links}
    consistent = {isin for isin, link in links if link.agreement is Agreement.CONSISTENT}
    issuer_named = {
        isin
        for statement in dataset.compliance_statements.values()
        for line in statement.exceptions
        for isin in line.isins
    } & listed
    return [
        ("listed in a reviewed trustee breach report", len(listed)),
        ("named in a trustee's notice to its holders", len(named)),
        ("the trustee cites a dated trust deed or trustee agreement", len(with_deed)),
        ("the report itself prints the clause or the required level", len(text_printed)),
        ("the issuer's or its auditor's statement names the covenant breached", len(issuer_named)),
        ("at least one clause transcribed in this dataset", len(transcribed)),
        ("reported breach linked to a transcribed clause", len(linked)),
        ("... and the two agree", len(consistent)),
        ("a candidate contract document located, not retrievable by the pipeline", len(located)),
        ("the contract itself retrieved, hashed and linked", len(retrieved)),
    ]


def _heading_section(dataset: Dataset) -> str:
    retrieved = [d.retrieved_at.date() for d in dataset.documents.values() if d.retrieved_at]
    return (
        "# Observability report\n\n"
        "Generated by `brdo report` from the records in `data/`. Figures describe what the reviewed public documents "
        "state and what could be traced. They are not findings about whether any issuer or trustee complied with any "
        "obligation, and the absence of a reported breach is not evidence that none occurred.\n\n"
        f"Documents retrieved between {min(retrieved, default='n/a')} and {max(retrieved, default='n/a')}. "
        f"Records: {len(dataset.instruments)} instruments, {len(dataset.issuers)} issuers, "
        f"{len(dataset.documents)} documents, {len(dataset.breach_reports)} breach reports, "
        f"{len(dataset.breach_notices)} notices, {len(dataset.provisions)} contract clauses, "
        f"{len(dataset.searches)} logged searches, {len(dataset.discrepancies)} discrepancies."
    )


def main_period(dataset: Dataset) -> date | None:
    """The quarter with the most trustees reviewed, which is the one the sample is built on."""
    trustees: dict[date, set[str]] = defaultdict(set)
    for report in dataset.breach_reports.values():
        trustees[report.period.end].add(report.trustee)
    return max(trustees, key=lambda end: len(trustees[end]), default=None)


def _trustee_section(dataset: Dataset) -> str:
    period = main_period(dataset)
    if period is None:
        return ""
    rows = []
    for source in sorted(dataset.sources.values(), key=lambda s: s.id):
        if source.kind is not SourceKind.DEBENTURE_TRUSTEE:
            continue
        searches = [
            s for s in dataset.searches.values() if s.subject == source.id and s.purpose is SearchPurpose.TRUSTEE_REPORT
        ]
        if not searches:
            continue
        reports = [r for r in dataset.breach_reports.values() if r.trustee == source.id and r.period.end == period]
        isins = {isin for report in reports for row in report.rows for isin in row.isins}
        issuers = {row.issuer for report in reports for row in report.rows}
        rows.append(
            [
                source.name,
                searches[0].outcome.value,
                len(reports),
                len(issuers),
                len(isins),
                "nil table" if any(r.nil_report for r in reports) else "",
                "yes" if source.ai_training.value == "reserved" else "",
            ]
        )
    return (
        f"## Trustees reviewed for the quarter ended {period:%d %B %Y}\n\n"
        "Only trustees with a logged search are shown. A `not_found` means the report did not surface through the "
        "steps logged, not that none was published.\n\n"
        + _table(["trustee", "search outcome", "versions", "issuers", "ISINs", "note", "AI training reserved"], rows)
    )


def _reports_section(dataset: Dataset) -> str:
    rows = []
    for document_id in sorted(dataset.breach_reports):
        report = dataset.breach_reports[document_id]
        document = dataset.documents[document_id]
        rows.append(
            [
                document_id,
                report.period.end,
                document.as_of or "",
                ", ".join(document.supersedes),
                len({row.row for row in report.rows}),
                len({isin for row in report.rows for isin in row.isins}),
                len(report.no_information),
                sum(row.transcribed_from_rendering for row in report.rows),
            ]
        )
    return "## Breach status reports transcribed\n\n" + _table(
        [
            "report",
            "period end",
            "as of",
            "supersedes",
            "serials",
            "ISINs",
            "no-information issuers",
            "rows read from the rendering",
        ],
        rows,
    )


def _revisions_section(dataset: Dataset) -> str:
    rows = [[r.isin, r.earlier, r.later, r.field, r.before, r.after] for r in revisions(dataset)]
    if not rows:
        return "## Revisions between report versions\n\nNone detected."
    return (
        "## Revisions between report versions\n\nDetected by comparing a report with the later version that supersedes "
        "it.\n\n" + _table(["ISIN", "earlier", "later", "field", "before", "after"], rows)
    )


def _specificity_section(dataset: Dataset) -> str:
    counts: dict[str, Counter] = defaultdict(Counter)
    for report in dataset.breach_reports.values():
        for row in report.rows:
            for item in row.items:
                counts[report.document][item.specificity] += len(item.isins)
    rows = [
        [document_id] + [counts[document_id].get(level, 0) for level in CovenantSpecificity]
        for document_id in sorted(counts)
    ]
    return (
        "## How much of the contract each report prints\n\n"
        "Counted per ISIN and covenant cell. This shows how far a reader can get from the report alone.\n\n"
        + _table(["report"] + [level.value for level in CovenantSpecificity], rows)
    )


def _dates_section(dataset: Dataset) -> str:
    notes = [
        [document_id, note.text]
        for document_id, report in sorted(dataset.breach_reports.items())
        for note in report.printed_notes
        if "date of" in note.text.lower()
    ]
    rows = []
    for document_id in sorted(dataset.breach_reports):
        report = dataset.breach_reports[document_id]
        serials: dict[str, tuple[date | None, date | None]] = {}
        for row in report.rows:
            serials.setdefault(
                row.row,
                (row.actual_breach.value if row.actual_breach else None, row.detected.value if row.detected else None),
            )
        if not serials:
            continue
        at_period_end = sum(actual == report.period.end for actual, _ in serials.values())
        same_as_detected = sum(actual is not None and actual == detected for actual, detected in serials.values())
        intervals = [(d - a).days for a, d in serials.values() if a and d]
        rows.append([document_id, len(serials), at_period_end, same_as_detected, _spread(intervals)])
    return (
        "## What the date columns mean\n\n"
        "Reports define their own date columns, and the definitions differ, so an interval from one report is not "
        "comparable with one from another. Printed definitions:\n\n"
        + _table(["report", "printed note"], notes)
        + "\n\nHow the date of actual breach is used, per printed serial number. The interval is detection date minus "
        "actual-breach date as printed (min / median / max); it is arithmetic on printed dates, not an assessment of "
        "delay. The reports' own delay columns are kept verbatim in the exports.\n\n"
        + _table(["report", "serials", "actual = period end", "actual = detected", "interval in days"], rows)
    )


def _actions_section(dataset: Dataset) -> str:
    counts: dict[str, Counter] = defaultdict(Counter)
    for document_id, report in dataset.breach_reports.items():
        for serial in {row.row for row in report.rows}:
            kinds = {action.kind for row in report.rows if row.row == serial for action in row.actions}
            counts[document_id].update(kinds)
    kinds = [kind for kind in ActionKind if any(counts[d].get(kind) for d in counts)]
    rows = [[d] + [counts[d].get(kind, 0) for kind in kinds] for d in sorted(counts)]
    continuations = [n for n in dataset.breach_notices.values() if n.kind is NoticeKind.MEETING_CONTINUATION]
    no_quorum = {isin for n in continuations if n.adjourned_for_lack_of_quorum for isin in n.isins}
    return (
        "## Follow-up reported\n\nPrinted serial numbers per report whose action cells report each kind of "
        "follow-up, as read by the project.\n\n"
        + _table(["report"] + [kind.value for kind in kinds], rows)
        + f"\n\nFollow-up letters in the reviewed files say a holders' meeting was adjourned for lack of quorum for "
        f"{len(no_quorum)} ISINs. Only some trustees publish such letters, so this is a floor, not a rate."
    )


def _consistency_section(dataset: Dataset) -> str:
    comparisons = compare_notices_with_reports(dataset)
    dated = [c for c in comparisons if c.days_from_intimation_to_detection is not None]
    same_day = [c for c in dated if c.days_from_intimation_to_detection == 0]
    threshold_checked = [c for c in comparisons if c.thresholds_agree is not None]
    agree = [c for c in threshold_checked if c.thresholds_agree]
    differing = [
        [c.isin, c.report, c.row, c.issuer_intimation, c.detected, c.days_from_intimation_to_detection]
        for c in dated
        if c.days_from_intimation_to_detection != 0
    ]
    thresholds = [
        [c.isin, c.report, ", ".join(sorted(c.thresholds_in_notice or [])), ", ".join(sorted(c.thresholds_in_report))]
        for c in threshold_checked
        if not c.thresholds_agree
    ]
    section = (
        "## Do a trustee's report and its own notices agree?\n\n"
        f"{len(comparisons)} ISIN-level comparisons between a report row and the same trustee's notice for the same "
        f"quarter. On dates, the detection date printed in the report equals the date the notice says the issuer "
        f"informed the trustee in {len(same_day)} of {len(dated)} comparisons. On covenant levels, the percentages, "
        f"multiples and crore amounts printed in the two match exactly in {len(agree)} of {len(threshold_checked)} "
        "comparisons where the notice prints any. This checks numbers only, so it cannot see a change of wording or "
        "duration around the same number; see discrepancy dvara-cost-to-income-limit. Both publications come from "
        "the same trustee, so agreement between them is not independent corroboration. Differences are listed as "
        "they are, and may have ordinary explanations.\n\n"
        "Detection date differs from the stated date of intimation:\n\n"
        + _table(["ISIN", "report", "row", "intimated per notice", "detected per report", "days"], differing)
    )
    if thresholds:
        section += "\n\nStated levels differ:\n\n" + _table(["ISIN", "report", "in notice", "in report"], thresholds)
    return section


_OUTCOME_RANK = [SearchOutcome.FOUND, SearchOutcome.LOCATED_NOT_RETRIEVED, SearchOutcome.ACCESS_ERROR]


def _statements_section(dataset: Dataset) -> str:
    period = main_period(dataset)
    searched: dict[str, set[SearchOutcome]] = defaultdict(set)
    for search in dataset.searches.values():
        if search.purpose is SearchPurpose.COMPLIANCE_STATEMENT and search.period and search.period.end == period:
            searched[search.subject].add(search.outcome)
    best = Counter(
        next((o for o in _OUTCOME_RANK if o in outcomes), SearchOutcome.NOT_FOUND) for outcomes in searched.values()
    )
    comparisons = [c for c in compare_statements_with_reports(dataset) if c.trustee_lists is not None]
    tally = Counter(c.agreement for c in comparisons)
    rows = [
        [
            c.isin,
            c.statement,
            c.made_by,
            c.scope,
            "breach" if c.statement_reports_breach else "compliance",
            c.trustee_report,
            "yes" if c.trustee_lists else "no",
            c.agreement,
            ", ".join(c.levels_only_in_statement),
        ]
        for c in sorted(comparisons, key=lambda c: (c.agreement, c.isin, c.statement))
    ]
    return (
        "## Issuers' own statements set beside the trustee's report\n\n"
        "Issuers must give their trustee an auditor-certified statement of financial covenant compliance "
        "every quarter, "
        "and must keep the compliance reports they file on their own website (regulation 62(1)(g) of the LODR "
        "Regulations). These statements are the issuer's or its auditor's, so they are a check on the trustee's report "
        "that does not come from the trustee.\n\n"
        f"For the quarter ended {period}, logged searches covered {len(searched)} issuers: a statement was found for "
        f"{best[SearchOutcome.FOUND]}, located but not retrievable by the pipeline for "
        f"{best[SearchOutcome.LOCATED_NOT_RETRIEVED]}, and not found for {best[SearchOutcome.NOT_FOUND]}.\n\n"
        f"Set beside the trustee's report for the same quarter, {tally[Agreement.CONSISTENT]} ISIN-level comparisons "
        f"agree, {tally[Agreement.DIFFERS]} differ and {tally[Agreement.NOT_COMPARABLE]} cannot be compared because "
        "the statement's stated scope does not reach the listed covenant. A statement limited to financial covenants "
        "says nothing about other undertakings. The last column lists required levels the statement prints that the "
        "trustee's report does not print for that ISIN.\n\n"
        + _table(
            [
                "ISIN",
                "statement",
                "made by",
                "covers",
                "says",
                "trustee report",
                "lists ISIN",
                "agreement",
                "levels only in statement",
            ],
            rows,
        )
    )


def _status_section(dataset: Dataset) -> str:
    by_period: dict[date, Counter] = {}
    for status in derive_all(dataset):
        by_period.setdefault(status.period_end, Counter())[status.status] += 1
    rows = [
        [period_end] + [by_period[period_end].get(category, 0) for category in CoverageStatus]
        for period_end in sorted(by_period)
    ]
    return (
        "## Breach-disclosure status by reporting period\n\n"
        "Derived for every instrument in the dataset by `brdo status`. The sample starts from ISINs that trustees "
        "listed, so these counts describe this sample, not the market. `no_report_found` means the reviewed sources do "
        "not list the instrument; it never means the instrument was compliant.\n\n"
        + _table(["period end"] + [category.value for category in CoverageStatus], rows)
    )


def _funnel_section(dataset: Dataset) -> str:
    return (
        "## Tracing reported breaches back to contracts\n\n"
        "ISINs at each stage, out of those listed in a reviewed report. The stages are not nested.\n\n"
        + _table(["stage", "ISINs"], [[label, count] for label, count in linkage_funnel(dataset)])
    )


def _evolution_section(dataset: Dataset) -> str:
    multi = sorted(
        (
            (isin, notice)
            for notice in dataset.breach_notices.values()
            if notice.kind is NoticeKind.BREACH and len(notice.deed_dates) > 1
            for isin in notice.isins
        ),
        key=lambda pair: pair[0],
    )
    seen, rows = set(), []
    for isin, notice in multi:
        if isin not in seen:
            seen.add(isin)
            rows.append([isin, ", ".join(str(d) for d in notice.deed_dates), notice.document])
    amended = [
        [p.instruments[0], p.amends, p.id, p.document]
        for p in sorted(dataset.provisions.values(), key=lambda p: p.id)
        if p.amends
    ]
    section = (
        "## Contractual evolution\n\nInstruments for which a trustee cites more than one deed date; the notices do not "
        "always say which deed amends which.\n\n" + _table(["ISIN", "deed dates cited", "notice"], rows)
    )
    if amended:
        section += "\n\nClauses recorded with both their earlier and later text:\n\n" + _table(
            ["ISIN", "earlier clause", "later clause", "source"], amended
        )
    return section


def _discrepancy_section(dataset: Dataset) -> str:
    conflicts = []
    for isin, instrument in sorted(dataset.instruments.items()):
        values = sorted({str(c.value) for c in instrument.claims if c.property is InstrumentProperty.DEBENTURE_TRUSTEE})
        if len(values) > 1:
            conflicts.append([isin, ", ".join(values)])
    rows = [
        [d.id, d.kind.value, d.status.value, d.subject]
        for d in sorted(dataset.discrepancies.values(), key=lambda d: d.id)
    ]
    return (
        "## Discrepancies kept open\n\n"
        + _table(["id", "kind", "status", "subject"], rows)
        + "\n\nInstruments whose debenture trustee is stated differently by different sources:\n\n"
        + (_table(["ISIN", "trustees claimed"], conflicts) if conflicts else "None recorded.")
    )


def _clauses_section(dataset: Dataset) -> str:
    counts = Counter(p.category.value for p in dataset.provisions.values())
    sources = Counter(dataset.documents[p.document].type.value for p in dataset.provisions.values())
    return (
        "## Contract clauses transcribed\n\nBy SEBI covenant category (Annex-VIA):\n\n"
        + _table(["category", "clauses"], [list(item) for item in sorted(counts.items())])
        + "\n\nBy the kind of document stating them. "
        + (
            "None of these is the contract itself."
            if not any(
                dataset.documents[p.document].type in CONTRACT_DOCUMENT_TYPES for p in dataset.provisions.values()
            )
            else "Contract documents are included."
        )
        + "\n\n"
        + _table(["document type", "clauses"], [list(item) for item in sorted(sources.items())])
    )


def _manual_queue_section(dataset: Dataset) -> str:
    rows = [
        [s.subject, url, s.note or ""]
        for s in sorted(dataset.searches.values(), key=lambda s: s.id)
        if s.outcome is SearchOutcome.LOCATED_NOT_RETRIEVED
        for url in s.urls_seen
    ]
    return (
        "## Candidates awaiting manual retrieval\n\n"
        "These sources refuse or forbid automated retrieval. Each file can be downloaded in a browser and ingested "
        "with `brdo add-document --from-file`, which hashes it so that others can verify they hold the same file. None "
        "has been ingested, and none is cited as evidence.\n\n" + _table(["ISIN", "where", "note"], rows)
    )


def _search_section(dataset: Dataset) -> str:
    counts = sorted(Counter((s.purpose.value, s.outcome.value) for s in dataset.searches.values()).items())
    documents = Counter(d.type for d in dataset.documents.values())
    return (
        "## Search log outcomes\n\n"
        + _table(["purpose", "outcome", "searches"], [[p, o, n] for (p, o), n in counts])
        + f"\n\nDocuments held by type: {documents.get(DocumentType.TRUSTEE_BREACH_STATUS_REPORT, 0)} breach reports, "
        f"{documents.get(DocumentType.TRUSTEE_PRESS_RELEASE, 0)} trustee notices, "
        f"{documents.get(DocumentType.ISSUER_FILING, 0)} issuer filings, "
        f"{documents.get(DocumentType.RATING_RATIONALE, 0)} rating rationales, "
        f"{documents.get(DocumentType.REGULATORY_CIRCULAR, 0)} regulatory circulars."
    )


def render_report(dataset: Dataset) -> str:
    sections = [
        _heading_section(dataset),
        _trustee_section(dataset),
        _reports_section(dataset),
        _revisions_section(dataset),
        _specificity_section(dataset),
        _dates_section(dataset),
        _actions_section(dataset),
        _consistency_section(dataset),
        _statements_section(dataset),
        _status_section(dataset),
        _funnel_section(dataset),
        _evolution_section(dataset),
        _clauses_section(dataset),
        _discrepancy_section(dataset),
        _manual_queue_section(dataset),
        _search_section(dataset),
    ]
    return "\n\n".join(section for section in sections if section) + "\n"
